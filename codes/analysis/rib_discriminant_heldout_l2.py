def _r2(pred, true):
    pred = np.asarray(pred, float); true = np.asarray(true, float)
    m = np.isfinite(pred) & np.isfinite(true)
    pred, true = pred[m], true[m]
    ss = np.sum((true - true.mean()) ** 2)
    return float(1.0 - np.sum((pred - true) ** 2) / ss) if ss > 0 else np.nan


def score_geometry(tag):
    """Score one operating-map geometry through the 4 eddy closures (no resolved
    uv -> no exact-stress oracle arm, B-L2-2), recompute eps_med under the
    Y_IDX=10 protocol, the conditioning floor (median + p90 kappa), and a
    variance-robust accuracy metric relRMS = RMS error / mean|tau_w| (which,
    unlike R^2, does not blow up when tau_w has vanishing variance)."""
    d = np.load(os.path.join(RESULTS, tag + "_wall_profiles.npz"), allow_pickle=True)
    y, U, tw, dpdx = d["y"], d["U"], d["tau_w"], d["dp_dx"]
    nu = float(d["nu"]) if np.size(d["nu"]) == 1 else float(np.asarray(d["nu"]).ravel()[0])
    clo = {c["key"]: c for c in CC.CLOSURES}
    n = y.shape[0]
    eps = []
    preds = {c: [] for c in EDDY}
    kaps = {c: [] for c in EDDY}
    trues = []
    for j in range(n):
        yj, Uj = y[j], U[j]
        if Y_IDX + 1 >= len(yj):
            continue
        y_m, U_m, dp, t = yj[Y_IDX], Uj[Y_IDX], float(dpdx[j]), float(tw[j])
        if y_m <= 0 or not np.isfinite(U_m) or abs(t) < TW_FLOOR:
            continue
        den = abs(dp) * y_m
        if den <= EPS_FLOOR:
            continue
        eps.append(abs(t) / den)
        trues.append(t)
        prof = {"y": yj, "U": Uj}
        for c in EDDY:
            preds[c].append(CC.predict_tau_w(clo[c], U_m, y_m, dp, nu, prof))
            k, _ = CC.kappa_closure(clo[c], U_m, y_m, dp, nu, prof, t)
            kaps[c].append(k)
    eps = np.asarray(eps, float)
    trues = np.asarray(trues, float)
    r2 = {c: _r2(preds[c], trues) for c in EDDY}
    r2_best = max(v for v in r2.values() if np.isfinite(v))
    r2_worst = min(v for v in r2.values() if np.isfinite(v))
    p90 = {}
    medk = {}
    for c in EDDY:
        kf = np.asarray(kaps[c], float)
        kf = kf[np.isfinite(kf)]
        p90[c] = float(np.nanpercentile(kf, 90)) if kf.size else np.nan
        medk[c] = float(np.nanmedian(kf)) if kf.size else np.nan
    # variance-robust accuracy on the production closure A (ML van Driest)
    pA = np.asarray(preds["A_ml_vandriest"], float)
    m = np.isfinite(pA) & np.isfinite(trues)
    mean_abs = float(np.mean(np.abs(trues[m]))) + 1e-30
    relRMS = float(np.sqrt(np.mean((pA[m] - trues[m]) ** 2)) / mean_abs)
    cv_tw = float(np.std(trues[m]) / mean_abs)
    return dict(
        tag=tag,
        a_over_delta=float(d["a_over_delta"]),
        lambda_over_delta=float(d["lambda_over_delta"]),
        f_sep=float(d["f_sep"]),
        provenance=str(d["provenance"]),
        n_stations=int(len(eps)),
        eps_med=float(np.nanmedian(eps)) if eps.size else np.nan,
        eps_med_stored=float(d["eps_median"]),
        r2=r2, r2_best=float(r2_best), r2_worst=float(r2_worst),
        p90_kappa=p90, med_kappa=medk,
        med_kappa_A=float(medk["A_ml_vandriest"]),
        relRMS=relRMS, cv_tw=cv_tw,
    )


def oracle_law_trend_only():
    """B-L2-1: re-confirm ONLY the Spearman trend of the oracle-amplification law.
    We deliberately DO NOT report or use any power-law crossing eps."""
