# (R2) commensurate averaging-window sensitivity
# ---------------------------------------------------------------------------
def window_sensitivity(l2, case: Path, truth_phase, truth_tau) -> dict[str, Any]:
    """Score EVERY checkpoint in the same E_tau / R^2 estimand as station+grid."""
    _, _, curves, _ = HM.load_case(l2, case)
    names = list(curves)
    if len(names) < 3:
        raise SystemExit(f"{case}: fewer than three checkpoints")
    t0 = 135.0
    cont = None
    for key, spec in HR.CONTINUATIONS.items():
        if spec["case_id"] == case.name and spec["bundle"] == case.parent.name:
            cont = spec
    if cont is not None:
        t0 = float(cont["drive_t0"])
    per = {}
    for name in names:
        m = l2.metrics(curves[name], truth_phase, truth_tau)
        per[name] = {
            "checkpoint_time": float(name),
            "window_length": float(name) - t0,
            "relative_rms": float(m["relative_rms"]),
            "r2": float(m["r2"]),
        }
    ordered = sorted(per.values(), key=lambda r: r["checkpoint_time"])
    e = [r["relative_rms"] for r in ordered]
    r2 = [r["r2"] for r in ordered]
    return {
        "window_origin": t0,
        "per_checkpoint": per,
        "window_lengths": [r["window_length"] for r in ordered],
        # SAME estimand as station and grid: differences of E_tau (and of R^2)
        "delta_Etau_180_to_225": float(e[1] - e[0]),
        "delta_Etau_225_to_270": float(e[2] - e[1]),
        "max_abs_delta_Etau": float(max(abs(e[1] - e[0]), abs(e[2] - e[1]))),
        "delta_R2_180_to_225": float(r2[1] - r2[0]),
        "delta_R2_225_to_270": float(r2[2] - r2[1]),
        "max_abs_delta_R2": float(max(abs(r2[1] - r2[0]), abs(r2[2] - r2[1]))),
        "estimand": "E_tau = RMS(tau_model - tau_DNS)/RMS(tau_DNS) on the 4096-point dense phase grid",
    }


