def drive_record(point: dict[str, Any]) -> dict[str, Any]:
    """Report the REGISTERED gate outcome and the exact constraint separately."""
    cb = point.get("crest_bulk", {}) or {}
    dr = point.get("drive_registration", {}) or {}
    st = point.get("drive_stationarity", {}) or {}
    measured = cb.get("crest_bulk_velocity_measured")
    registered = dr.get("crest_bulk_velocity_registered")
    ubar_dev = st.get("window_Ubar_max_abs_deviation")
    dev = (abs(float(measured) - 1.0) if isinstance(measured, (int, float)) else None)
    exact_ok = (
        isinstance(registered, (int, float)) and abs(float(registered) - 1.0) <= 1e-5
        and isinstance(ubar_dev, (int, float)) and float(ubar_dev) <= 1e-4
    )
    return {
        # the check that WAS registered, scored as registered -- no ceiling change
        "registered_single_slice_3pct_gate": {
            "measured_crest_bulk_z2p25": (float(measured) if measured is not None else None),
            "abs_deviation": dev,
            "threshold": 0.03,
            "outcome": (None if dev is None else ("PASS" if dev <= 0.03 else "FAIL")),
        },
        # the constraint that check existed to protect, bound exactly
        "exact_controller_volume_identity": {
            "crest_bulk_velocity_registered": registered,
            "window_Ubar_max_abs_deviation": ubar_dev,
            "registered_volume_average_Ubar": st.get("registered_volume_average_Ubar"),
            "mesh_total_volume": dr.get("mesh_total_volume"),
            "holds": bool(exact_ok),
        },
        # demoted: diagnostic only, no pass/fail authority
        "slice_flux_homogeneity_diagnostic": {
            "max_abs_deviation_fraction": cb.get("slice_flux_max_abs_deviation_fraction"),
            "expected_spanwise_mean": cb.get("slice_flux_expected_spanwise_mean"),
            "authority": "none: ancillary spanwise-homogeneity measurement, not an admission gate",
        },
    }


def spearman(a, b) -> float:
    a, b = np.asarray(a, float), np.asarray(b, float)
    ok = np.isfinite(a) & np.isfinite(b)
    if np.count_nonzero(ok) < 3:
        return math.nan
    ra = np.argsort(np.argsort(a[ok])).astype(float)
    rb = np.argsort(np.argsort(b[ok])).astype(float)
    return float(np.corrcoef(ra, rb)[0, 1])


def permutation_p(a, b, draws: int, seed: int) -> float:
    """Two-sided permutation p for the Spearman statistic (n is small: n<=6)."""
    a, b = np.asarray(a, float), np.asarray(b, float)
    ok = np.isfinite(a) & np.isfinite(b)
    a, b = a[ok], b[ok]
    n = len(a)
    if n < 3:
        return math.nan
    obs = abs(spearman(a, b))
    rng = np.random.default_rng(seed)
    import itertools
    if n <= 8:                                   # exact
        perms = list(itertools.permutations(range(n)))
        hits = sum(1 for p in perms if abs(spearman(a, b[list(p)])) >= obs - 1e-12)
        return float(hits / len(perms))
    hits = sum(1 for _ in range(draws)
               if abs(spearman(a, b[rng.permutation(n)])) >= obs - 1e-12)
    return float((hits + 1) / (draws + 1))


