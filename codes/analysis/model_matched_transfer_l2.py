#!/usr/bin/env python3
"""model_matched_transfer_l2.py -- L2 instrument (development/nodes/node_010).

WHAT THIS IS
------------
The R2-3/M6 coupled matching-surface campaign (14 logical cases, terminal on
ARCHER2) is sound raw data.  Its *reduction* carried four estimand defects that
made the published comparison unfair.  This script is the replacement
measurement instrument.  It runs on the already-deposited terminal campaign; it
launches nothing and re-runs no CFD.

The four repairs, each of which changes a number that appears in the paper:

  (R1) MODEL IDENTITY.  ``harvest_r2_3_ym.py`` interpolates ONE a-priori sweep
       (``epsilon_coupled_predictor.npz``, generated by the pressure-gradient
       ODE architecture ``ode_wall_model.predict_tau_w``) and writes it into
       BOTH the equilibrium and the total-gradient-TBLE rows, byte-identically.
       Any "a-priori -> coupled transfer" statistic computed from that column
       compares coupled equilibrium against a pressure-gradient a-priori model.
       Here each coupled arm is paired with the a-priori evaluation of ITS OWN
       deployed architecture, and the pairing is *proved* by reading the
       OpenFOAM ``nut`` boundary condition out of every case:

           nutUSpaldingWallFunction  <->  M0_equilibrium  (Spalding)
           totalGradientTbleNut      <->  M1_pressure_gradient_ode

       The a-priori model is evaluated at the coupled run's own measured
       per-face matching surface (phase, y_m), i.e. the same physical surface,
       so only the model architecture differs between the two branches.

  (R2) COMMENSURATE SENSITIVITY.  The deposited averaging-window sensitivity is
       RMS(tau_270 - tau_225)/RMS(tau_270), a curve-difference norm, while the
       station and grid sensitivities are differences of E_tau.  Their ratio is
       not a dominance statement.  Here every checkpoint (windows 180/225/270)
       is scored against the same DNS truth in the same E_tau and R^2 estimands
       used for station and grid, so all three sensitivities are differences of
       one quantity.

  (R3) CASE-CORRECT CRITICAL HEIGHT.  ``YCRIT_PAPER = 15.925931`` is the
       ``krank_pehill_Re10595`` row of ``critical_matching_height_map.npz``.
       The case under test is the Xiao Re_H=5600 hill, whose own row is
       ``periodic_hills_1p0`` with y_crit+ = 1.0 -- the lower edge of the
       swept y+ grid, i.e. no interior crossing.  This script uses the
       case's own row and reports where the sampled surfaces sit relative to it.

  (R4) DRIVE-GATE PROVENANCE.  The registered admission check was "measured
       crest bulk within 3%" on a single z = 2.25 sample line.  Two points fail
       it.  This script records that outcome as FAILED, binds the corrected
       drive to the exact controller/volume identity instead, and demotes the
       slice fluxes to an ancillary spanwise-homogeneity diagnostic with no
       pass/fail authority.  No post-outcome ceiling is applied.

Outputs
-------
    codes/results/model_matched_transfer_l2_<date>.npz
    codes/results/model_matched_transfer_l2_<date>_summary.json

Exit 0 only if every internal consistency assertion holds.
"""

