def wall_model_constants(case: Path, model: str) -> dict[str, Any]:
    """Constants the coupled arm deployed, read from the case where declared."""
    text = (case / "input" / "nut").read_text(errors="replace")
    m = re.search(rf"^\s*bottomWall\s*$\s*\{{(.*?)\n    \}}", text, re.MULTILINE | re.DOTALL)
    body = m.group(1) if m else ""
    body = re.sub(r"value\s+nonuniform.*?\n\)\n;", "", body, flags=re.DOTALL)
    def declared(name):
        d = re.search(rf"\b{name}\s+([0-9.eE+-]+)\s*;", body)
        return float(d.group(1)) if d else None
    kappa, E, aplus = declared("kappa"), declared("E"), declared("Aplus")
    if model == "equilibrium":
        return {
            "kappa": kappa if kappa is not None else KAPPA_DEPLOYED,
            "E": E if E is not None else E_DEPLOYED,
            "B": (math.log(E if E is not None else E_DEPLOYED)
                  / (kappa if kappa is not None else KAPPA_DEPLOYED)),
            "declared_in_case": {"kappa": kappa is not None, "E": E is not None},
            "source": ("case dictionary" if (kappa is not None and E is not None)
                       else "OpenFOAM Foundation 10 nutUSpaldingWallFunction defaults "
                            "(the case declares only the BC type)"),
        }
    return {
        "kappa": kappa if kappa is not None else KAPPA_DEPLOYED,
        "A_plus": aplus if aplus is not None else A_PLUS_DEPLOYED,
        "declared_in_case": {"kappa": kappa is not None, "Aplus": aplus is not None},
        "source": ("case dictionary" if (kappa is not None and aplus is not None)
                   else "totalGradientTbleNutFvPatchScalarField.C:135-136 "
                        "(kappa = 0.41, Aplus = 26.0, hard-coded in the deployed kernel)"),
    }


def spalding_at_surface(fields, phase, y_m, kappa: float, b_const: float) -> np.ndarray:
    """M0 exactly as the deployed nutUSpaldingWallFunction defines it."""
    x_targets = np.mod(np.asarray(phase, float), 1.0) * C.LX
    tau = np.empty(len(x_targets))
    for j, (xt, ym) in enumerate(zip(x_targets, np.asarray(y_m, float))):
        i = int(np.argmin(np.abs(fields.x - xt)))
        u_m, _, _ = fields.station(i, ym)
        tau[j] = (C.wm.spalding_wall_stress(u_m, ym, C.NU, kappa=kappa, b_const=b_const)
                  if abs(u_m) > 1e-12 else 0.0)
    return tau


def apriori_at_surface(fields, phase, y_m, member, truth_phase, truth_tau,
                       draws: int, seed: int, b_const: float = B_DEPLOYED,
                       kappa: float = KAPPA_DEPLOYED) -> dict[str, Any]:
    """Evaluate ONE ladder member at the coupled run's own matching surface."""
    if member == "M0_equilibrium":
        tau = spalding_at_surface(fields, phase, y_m, kappa, b_const)
        diag = {"roots_M1": np.full(len(phase), np.nan)}
    else:
        preds, diag = C.ladder_predictions(fields, phase, y_m, models=(member,))
        tau = preds[member]
    if not np.all(np.isfinite(tau)):
        raise SystemExit(f"{member}: non-finite a-priori prediction")
    m, dense, truth_dense, pred_dense = C.phase_metrics(phase, tau, truth_phase, truth_tau)
    samples = C.block_bootstrap_relative_rms(truth_dense, {("a", member): pred_dense},
                                             draws=draws, block=BLOCK, seed=seed)
    return {
        "member": member,
        "relative_rms": m["relative_rms"],
        "r2": m["r2"],
        "relative_rms_interval": C.interval(samples[("a", member)]),
        "sign_accuracy": m["sign_accuracy"],
        "signed_force_ratio": m["signed_force_ratio"],
        "reversed_fraction": m["reversed_fraction"],
        "roots_M1_max": (float(np.nanmax(diag["roots_M1"]))
                         if member == "M1_pressure_gradient_ode" else None),
        "_pred": tau,
    }


